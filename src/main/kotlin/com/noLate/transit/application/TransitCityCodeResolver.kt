import com.noLate.transit.domain.TransitCityCodeNamespace
import org.springframework.stereotype.Component

sealed interface TransitCityResolution {
    data object Absent : TransitCityResolution
    data object Unsupported : TransitCityResolution
    data object Seoul : TransitCityResolution
    data class Tago(val code: String) : TransitCityResolution
}

/** ODsay CID와 국토부 TAGO cityCode의 서로 다른 namespace를 명시적으로 변환한다. */
