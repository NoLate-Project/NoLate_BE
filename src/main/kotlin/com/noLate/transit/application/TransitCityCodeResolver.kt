            "검증된 ODsay 도시코드 매핑 개수가 변경되었습니다. 공식 표를 다시 대조해야 합니다."
        }
        check(ODSAY_TO_TAGO.values.all(TAGO_CODES::contains)) {
            "ODsay 도시코드 매핑은 현재 TAGO 공식 도시코드만 가리켜야 합니다."
        }
    }

    fun resolve(
        rawCode: String?,
        namespace: TransitCityCodeNamespace,
    ): TransitCityResolution {
        val code = rawCode?.trim()?.takeIf(String::isNotBlank)
            ?: return TransitCityResolution.Absent
        if (!code.all(Char::isDigit)) return TransitCityResolution.Unsupported

        if (namespace == TransitCityCodeNamespace.ODSAY_CID && code == ODSAY_SEOUL_CID) {
            return TransitCityResolution.Seoul
        }
        val tagoCode = when (namespace) {
            TransitCityCodeNamespace.TAGO -> code.takeIf(TAGO_CODES::contains)
            TransitCityCodeNamespace.ODSAY_CID -> ODSAY_TO_TAGO[code]
            TransitCityCodeNamespace.UNKNOWN -> null
        } ?: return TransitCityResolution.Unsupported
        return TransitCityResolution.Tago(code = tagoCode)
    }

